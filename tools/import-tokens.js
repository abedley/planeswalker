#!/usr/bin/env node
/**
 * Imports art for the game's tokens from Scryfall into src/cards/tokenArt.js.
 *
 * Finds every token the cards, sample decks and campaigns can create (plus Treasure,
 * Food and Clue), and looks for a printed Scryfall token with the same name, type,
 * power/toughness, colors and keywords: first the token printed alongside a card
 * that creates it (its "related" token), else the best printing from a search.
 * Tokens that already have art keep it, unless --refresh. Node-only: nothing in
 * the site imports this file.
 *
 * Usage:
 *   node tools/import-tokens.js
 *   node tools/import-tokens.js --refresh    (pick every token's printing again)
 *   node tools/import-tokens.js --dry-run    (report only, write nothing)
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { CARDS } from '../src/cards/cards.js';
import * as SAMPLES from '../src/cards/sampleCards.js';
import { SAMPLE_CAMPAIGN } from '../src/campaign/sampleCampaign.js';
import { CAMPAIGN } from '../src/campaign/realCampaign.js';
import { fetchCollection, searchCards } from './scryfall/client.js';
import { collectTokens, describeToken, pickTokenPrinting, tokenPresentation, tokenQuery } from './scryfall/tokens.js';

const OUTPUT = fileURLToPath(new URL('../src/cards/tokenArt.js', import.meta.url));
const NAME = 'TOKEN_PRESENTATION';

const HEADER = `// Generated by tools/import-tokens.js from Scryfall data. Don't edit by hand:
// re-run the importer instead (see README).
`;

export function renderTokenArtModule(presentation) {
  const sorted = Object.fromEntries(Object.entries(presentation).sort(([a], [b]) => a.localeCompare(b)));
  return `${HEADER}
/** Art and other presentation fields for tokens, keyed by the card id the game gives them (tokenCardId). */
export const ${NAME} = ${JSON.stringify(sorted, null, 2)};
`;
}

/** The module's presentation entries, parsed from its JSON (so a stale module cache can't interfere). */
export async function readTokenArt(path) {
  let text;
  try {
    text = await readFile(path, 'utf8');
  } catch (error) {
    if (error.code === 'ENOENT') return {};
    throw error;
  }
  const body = text.slice(text.indexOf('=', text.indexOf(`export const ${NAME} =`)) + 1);
  return JSON.parse(body.slice(0, body.lastIndexOf(';')));
}

/** The Scryfall ids of the tokens printed alongside these cards (`all_parts`), in order. */
async function relatedTokenIds(creators) {
  const ids = [...creators].map((id) => CARDS[id]?.scryfallId).filter(Boolean);
  if (!ids.length) return [];
  const { cards } = await fetchCollection(ids.map((id) => ({ id })));
  return [...new Set(cards.flatMap((card) => (card.all_parts ?? []).filter((part) => part.component === 'token').map((part) => part.id)))];
}

async function findPrinting(token, creators) {
  const related = await relatedTokenIds(creators);
  if (related.length) {
    const { cards } = await fetchCollection(related.map((id) => ({ id })));
    const printing = pickTokenPrinting(cards, token, related);
    if (printing) return printing;
  }
  try {
    return pickTokenPrinting(await searchCards(tokenQuery(token), { unique: 'art' }), token);
  } catch (error) {
    if (error.status === 404) return null; // No cards match the search.
    throw error;
  }
}

async function main() {
  const { values } = parseArgs({
    options: {
      refresh: { type: 'boolean', default: false },
      'dry-run': { type: 'boolean', default: false },
      help: { type: 'boolean', short: 'h', default: false },
    },
  });
  if (values.help) {
    console.log('Usage: node tools/import-tokens.js [--refresh] [--dry-run]');
    return;
  }

  const tokens = collectTokens([CARDS, ...Object.values(SAMPLES), SAMPLE_CAMPAIGN, CAMPAIGN]);
  const existing = await readTokenArt(OUTPUT);
  const presentation = {};
  const imported = [];
  const kept = [];
  const notFound = [];
  for (const [cardId, { token, creators }] of tokens) {
    const name = describeToken(token);
    if (existing[cardId] && !values.refresh) {
      presentation[cardId] = existing[cardId];
      kept.push(name);
      continue;
    }
    const printing = await findPrinting(token, creators);
    if (printing) {
      presentation[cardId] = tokenPresentation(printing);
      imported.push(`${name}: ${printing.name} (${printing.set.toUpperCase()} ${printing.collector_number}, ${printing.artist})`);
    } else {
      notFound.push(name);
    }
  }

  if (imported.length) console.log(`Imported (${imported.length}):\n${imported.map((n) => `  + ${n}`).join('\n')}`);
  if (kept.length) console.log(`Already had art (${kept.length}):\n${kept.map((n) => `  = ${n}`).join('\n')}`);
  if (notFound.length) console.log(`No matching Scryfall token (${notFound.length}), so generated art:\n${notFound.map((n) => `  ? ${n}`).join('\n')}`);
  if (values['dry-run']) {
    console.log('Dry run: nothing written.');
  } else {
    await writeFile(OUTPUT, renderTokenArtModule(presentation));
    console.log(`Wrote art for ${Object.keys(presentation).length} token(s) to src/cards/tokenArt.js.`);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(`Import failed: ${error.message}`);
    process.exitCode = 2;
  });
}
