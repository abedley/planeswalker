/** Reads and writes the generated src/cards/importedCards.js module. */
import { readFile, writeFile } from 'node:fs/promises';

const HEADER = `// Generated by tools/import-cards.js from Scryfall data. Don't edit by hand:
// re-run the importer instead (see README).
`;

const sortKeys = (object) => Object.fromEntries(Object.entries(object).sort(([a], [b]) => a.localeCompare(b)));

/**
 * `cards`: imported card definitions. `presentation`: art and other presentation
 * fields for cards defined by hand (src/cards/cards.js), which the app shows.
 */
export function renderImportedCardsModule(cards, presentation = {}) {
  return `${HEADER}export const IMPORTED_CARDS = ${JSON.stringify(sortKeys(cards), null, 2)};

/** Art and other presentation fields for the hand-written cards (Forest, Llanowar Elves). */
export const CARD_PRESENTATION = ${JSON.stringify(sortKeys(presentation), null, 2)};
`;
}

/**
 * The module's contents, `{ cards, presentation }`. Parses its JSON rather than
 * importing it, so a stale module cache can't interfere.
 */
export async function readImportedModule(path) {
  let text;
  try {
    text = await readFile(path, 'utf8');
  } catch (error) {
    if (error.code === 'ENOENT') return { cards: {}, presentation: {} };
    throw error;
  }
  const json = (name) => {
    const start = text.indexOf(`export const ${name} =`);
    if (start === -1) return {};
    // JSON escapes newlines inside strings, so the first ";" + newline ends the value.
    const body = text.slice(text.indexOf('=', start) + 1);
    const end = body.indexOf(';\n');
    return JSON.parse(end === -1 ? body.trim().replace(/;$/, '') : body.slice(0, end));
  };
  return { cards: json('IMPORTED_CARDS'), presentation: json('CARD_PRESENTATION') };
}

export async function readImportedCards(path) {
  return (await readImportedModule(path)).cards;
}

export async function writeImportedCards(path, cards, presentation = {}) {
  await writeFile(path, renderImportedCardsModule(cards, presentation));
}
