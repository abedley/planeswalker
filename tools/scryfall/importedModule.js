/** Reads and writes the generated src/cards/importedCards.js module. */
import { readFile, writeFile } from 'node:fs/promises';

const HEADER = `// Generated by tools/import-cards.js from Scryfall data. Don't edit by hand:
// re-run the importer instead (see README).
`;

const sortKeys = (object) => Object.fromEntries(Object.entries(object).sort(([a], [b]) => a.localeCompare(b)));

export function renderImportedCardsModule(cards) {
  return `${HEADER}export const IMPORTED_CARDS = ${JSON.stringify(sortKeys(cards), null, 2)};\n`;
}

/** Parses the module's JSON body rather than importing it, so a stale module cache can't interfere. */
export async function readImportedCards(path) {
  let text;
  try {
    text = await readFile(path, 'utf8');
  } catch (error) {
    if (error.code === 'ENOENT') return {};
    throw error;
  }
  const json = text.slice(text.indexOf('=') + 1).trim().replace(/;$/, '');
  return JSON.parse(json);
}

export async function writeImportedCards(path, cards) {
  await writeFile(path, renderImportedCardsModule(cards));
}
