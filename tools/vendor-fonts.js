#!/usr/bin/env node
/**
 * Vendors the symbol fonts the app uses, cut down to the glyphs it needs:
 * - Mana (https://mana.andrewgioia.com, font SIL OFL 1.1, CSS MIT): mana symbols,
 *   {T}, card types and keyword abilities;
 * - Keyrune (https://keyrune.andrewgioia.com, font SIL OFL 1.1): set symbols.
 *
 * Writes app/vendor/mana.woff2, app/vendor/keyrune.woff2 and app/vendor/symbols.css
 * (our own small stylesheet: Keyrune's CSS is GPL, so only codepoints are read
 * from it). Dev-only; needs npm and fonttools' pyftsubset with brotli
 * (`pip install fonttools brotli`; set PYFTSUBSET to its path if not on PATH).
 *
 * Also vendors the text fonts, stand-ins for the ones printed on cards (both SIL OFL
 * 1.1, from Google Fonts, Latin subset): Faustina for Beleren (names and type
 * lines) and Crimson Pro for MPlantin (rules text). `--text` does only these.
 *
 *   node tools/vendor-fonts.js [--text]
 */
import { execFileSync } from 'node:child_process';
import { mkdtemp, readFile, writeFile, mkdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const MANA = 'mana-font@1.18.0';
const KEYRUNE = 'keyrune@3.19.0';
const OUT = fileURLToPath(new URL('../app/vendor/', import.meta.url));

/** Mana glyphs: mana symbols, numbers, tap and untap, card types, keyword abilities. */
export const MANA_GLYPHS = [
  'w', 'u', 'b', 'r', 'g', 'c', 'x', ...Array.from({ length: 21 }, (_, i) => String(i)),
  'tap', 'untap',
  'creature', 'instant', 'sorcery', 'artifact', 'enchantment', 'land', 'planeswalker',
  ...['flying', 'first-strike', 'double-strike', 'deathtouch', 'lifelink', 'trample', 'menace', 'reach',
    'vigilance', 'haste', 'defender', 'indestructible', 'hexproof', 'ward'].map((k) => `ability-${k}`),
];

/** Keyrune set symbols: the sets the real cards are printed in. */
export const SETS = ['m19', 'm20', 'm21', 'fdn', 'ltr'];

/** The codepoint a stylesheet gives `.prefix-name::before` (or `:before`). */
export function codepoint(css, prefix, name) {
  const escaped = name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  // The rule may list several selectors: ".ms-planeswalker::before, .ms-watermark-planeswalker::before {".
  const match = new RegExp(`\\.${prefix}-${escaped}::?before[^{]*\\{\\s*content:\\s*"\\\\([0-9a-fA-F]+)"`).exec(css);
  if (!match) throw new Error(`No glyph for .${prefix}-${name}`);
  return match[1].toLowerCase();
}

function subset(source, codepoints, output) {
  const tool = process.env.PYFTSUBSET ?? 'pyftsubset';
  execFileSync(tool, [
    source, `--unicodes=${codepoints.map((c) => `U+${c}`).join(',')}`, '--flavor=woff2', `--output-file=${output}`,
    // Keep the name table, which carries the copyright and license notices.
    '--name-IDs=*', '--name-languages=*', '--name-legacy',
  ], { stdio: 'inherit' });
}

export function renderStylesheet({ mana, sets }) {
  const rule = (selector, cp) => `${selector}::before { content: "\\${cp}"; }`;
  return `/* Generated by tools/vendor-fonts.js. Symbol fonts by Andrew Gioia:
   Mana (https://mana.andrewgioia.com) and Keyrune (https://keyrune.andrewgioia.com),
   SIL OFL 1.1, cut down to the glyphs this app uses. See LICENSE.md. */
@font-face { font-family: Mana; src: url("mana.woff2") format("woff2"); font-display: block; }
@font-face { font-family: Keyrune; src: url("keyrune.woff2") format("woff2"); font-display: block; }

.ms, .ss {
  display: inline-block;
  font-style: normal;
  font-weight: normal;
  line-height: 1;
  text-transform: none;
  vertical-align: middle;
  speak: never;
  -webkit-font-smoothing: antialiased;
}
.ms { font-family: Mana; }
.ss { font-family: Keyrune; }
${Object.entries(mana).map(([name, cp]) => rule(`.ms-${name}`, cp)).join('\n')}
${Object.entries(sets).map(([name, cp]) => rule(`.ss-${name}`, cp)).join('\n')}
`;
}

/** The text fonts: family, the Google Fonts axes asked for, and the file stem per style. */
export const TEXT_FONTS = [
  { family: 'Faustina', axes: 'wght@500..800', files: { normal: 'faustina' } },
  { family: 'Crimson Pro', axes: 'ital,wght@0,400..600;1,400..600', files: { normal: 'crimson-pro', italic: 'crimson-pro-italic' } },
];

/** The Latin `@font-face` blocks of a Google Fonts stylesheet: `[{ style, weight, url }]`. */
export function latinFaces(css) {
  return [...css.matchAll(/\/\* latin \*\/\s*@font-face\s*\{([^}]*)\}/g)].map(([, body]) => ({
    style: /font-style:\s*(\w+)/.exec(body)[1],
    weight: /font-weight:\s*([\d ]+)/.exec(body)[1].trim(),
    url: /url\(([^)]+)\)/.exec(body)[1],
  }));
}

async function vendorTextFonts() {
  // A modern browser's user agent, so Google Fonts serves woff2.
  const headers = { 'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36' };
  const rules = [];
  await mkdir(OUT, { recursive: true });
  for (const { family, axes, files } of TEXT_FONTS) {
    const css = await (await fetch(`https://fonts.googleapis.com/css2?family=${family.replace(/ /g, '+')}:${axes}&display=swap`, { headers })).text();
    for (const { style, weight, url } of latinFaces(css)) {
      const file = `${files[style]}.woff2`;
      await writeFile(join(OUT, file), Buffer.from(await (await fetch(url)).arrayBuffer()));
      rules.push(`@font-face { font-family: "${family}"; font-style: ${style}; font-weight: ${weight}; font-display: swap; src: url("${file}") format("woff2"); unicode-range: U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD; }`);
    }
  }
  await writeFile(join(OUT, 'fonts.css'), `/* Generated by tools/vendor-fonts.js: Faustina and Crimson Pro (SIL OFL 1.1), Latin subset. See LICENSE.md. */\n${rules.join('\n')}\n`);
  console.log(`Wrote ${rules.length} text font files to app/vendor/.`);
}

async function main() {
  if (process.argv.includes('--text')) {
    await vendorTextFonts();
    return;
  }
  // `--symbols`: only the symbol fonts.
  if (!process.argv.includes('--symbols')) await vendorTextFonts();
  const temp = await mkdtemp(join(tmpdir(), 'planeswalker-fonts-'));
  try {
    execFileSync('npm', ['pack', MANA, KEYRUNE, '--pack-destination', temp, '--silent'], { stdio: 'inherit' });
    for (const [pkg, dir] of [[MANA, 'mana'], [KEYRUNE, 'keyrune']]) {
      const [name, version] = pkg.split('@');
      await mkdir(join(temp, dir));
      execFileSync('tar', ['-xzf', join(temp, `${name}-${version}.tgz`), '-C', join(temp, dir)]);
    }
    const manaCss = await readFile(join(temp, 'mana/package/css/mana.css'), 'utf8');
    const keyruneCss = await readFile(join(temp, 'keyrune/package/css/keyrune.css'), 'utf8');
    const mana = Object.fromEntries(MANA_GLYPHS.map((name) => [name, codepoint(manaCss, 'ms', name)]));
    const sets = Object.fromEntries(SETS.map((name) => [name, codepoint(keyruneCss, 'ss', name)]));
    await mkdir(OUT, { recursive: true });
    subset(join(temp, 'mana/package/fonts/mana.ttf'), Object.values(mana), join(OUT, 'mana.woff2'));
    subset(join(temp, 'keyrune/package/fonts/keyrune.ttf'), Object.values(sets), join(OUT, 'keyrune.woff2'));
    await writeFile(join(OUT, 'symbols.css'), renderStylesheet({ mana, sets }));
    console.log(`Wrote ${Object.keys(mana).length} Mana glyphs and ${Object.keys(sets).length} set symbols to app/vendor/.`);
  } finally {
    await rm(temp, { recursive: true, force: true });
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
